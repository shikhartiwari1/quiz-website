const questions = [];
let currentQ = null;
let state = 'search'; // 'search' -> 'question' -> 'options' -> 'answer_wait' -> 'answer'
let idCounter = 1;

for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line) continue;

    if (line === '1 point') {
        if (currentQ) {
            questions.push(currentQ);
        }
        const currentId = idCounter++;
        currentQ = {
            id: String(currentId),
            question: currentId + ". " + lines[i + 1],
            options: [],
            answer: ""
        };
        i++; // skip the question line since we processed it
        state = 'options';
        continue;
    }

    if (state === 'options' && currentQ) {
        if (line.match(/^[a-d]\.\s/)) {
            currentQ.options.push(line);
        } else if (line === 'Yes, the answer is correct.' || line.startsWith('Score:') || line === 'Accepted Answers:') {
            if (line === 'Accepted Answers:') {
                state = 'answer';
            }
        }
    } else if (state === 'answer' && currentQ) {
        currentQ.answer = line;
        state = 'search'; // wait for next '1 point'
    }
}
if (currentQ) {
    questions.push(currentQ);
}

